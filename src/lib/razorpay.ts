import crypto from 'crypto';
import Razorpay from 'razorpay';

export interface RazorpayConfig {
  keyId: string;
  keySecret: string;
  webhookSecret: string;
  isConfigured: boolean;
  isTestMode: boolean;
  isLiveMode: boolean;
}

export function getRazorpayConfig(): RazorpayConfig {
  const keyId = (process.env.RAZORPAY_KEY_ID || process.env.NEXT_PUBLIC_RAZORPAY_KEY_ID || '').trim();
  const keySecret = (process.env.RAZORPAY_KEY_SECRET || '').trim();
  const webhookSecret = (process.env.RAZORPAY_WEBHOOK_SECRET || '').trim();

  const isConfigured = Boolean(
    keyId &&
      keySecret &&
      !keyId.includes('placeholder') &&
      !keySecret.includes('placeholder') &&
      !keyId.includes('your_razorpay')
  );

  const isTestMode = keyId.startsWith('rzp_test_');
  const isLiveMode = keyId.startsWith('rzp_live_');

  return {
    keyId,
    keySecret,
    webhookSecret,
    isConfigured,
    isTestMode,
    isLiveMode,
  };
}

let cachedRazorpayInstance: Razorpay | null = null;

export function getRazorpayClient(): Razorpay | null {
  const config = getRazorpayConfig();
  if (!config.isConfigured) {
    return null;
  }

  if (!cachedRazorpayInstance) {
    cachedRazorpayInstance = new Razorpay({
      key_id: config.keyId,
      key_secret: config.keySecret,
    });
  }

  return cachedRazorpayInstance;
}

/**
 * Validates the checkout return signature generated by Razorpay Checkout modal
 * (HMAC-SHA256 of `order_id|payment_id` against key_secret).
 */
export function verifyPaymentSignature({
  razorpayOrderId,
  razorpayPaymentId,
  signature,
  secret,
}: {
  razorpayOrderId: string;
  razorpayPaymentId: string;
  signature: string;
  secret: string;
}): boolean {
  if (!razorpayOrderId || !razorpayPaymentId || !signature || !secret) {
    return false;
  }

  try {
    const payload = `${razorpayOrderId}|${razorpayPaymentId}`;
    const expected = crypto.createHmac('sha256', secret).update(payload).digest('hex');

    const expectedBuffer = Buffer.from(expected, 'hex');
    const signatureBuffer = Buffer.from(signature, 'hex');

    if (expectedBuffer.length !== signatureBuffer.length) {
      return false;
    }

    return crypto.timingSafeEqual(expectedBuffer, signatureBuffer);
  } catch (err) {
    console.error('Signature verification error:', err);
    return false;
  }
}

/**
 * Validates Razorpay Webhook signature (`X-Razorpay-Signature`)
 * against raw webhook payload body.
 */
export function verifyWebhookSignature({
  bodyString,
  signature,
  webhookSecret,
}: {
  bodyString: string;
  signature: string;
  webhookSecret: string;
}): boolean {
  if (!bodyString || !signature || !webhookSecret) {
    return false;
  }

  try {
    const expected = crypto.createHmac('sha256', webhookSecret).update(bodyString).digest('hex');

    const expectedBuffer = Buffer.from(expected, 'hex');
    const signatureBuffer = Buffer.from(signature, 'hex');

    if (expectedBuffer.length !== signatureBuffer.length) {
      return false;
    }

    return crypto.timingSafeEqual(expectedBuffer, signatureBuffer);
  } catch (err) {
    console.error('Webhook signature verification error:', err);
    return false;
  }
}

